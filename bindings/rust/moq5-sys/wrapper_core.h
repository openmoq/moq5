/* The core tier moq5-sys binds by default, and the values bindgen cannot
 * read from it.
 *
 * bindgen turns `#define NAME 1u` into a constant but cannot evaluate
 * `UINT32_C(n)`, a cast such as `((moq_object_status_t)1)` or the
 * offsetof-based v0 floors. Each of those is restated here as a
 * `static const` whose initializer libclang evaluates; the build script
 * strips the MOQ5_SYSVAL_ prefix, so the generated crate exposes them under
 * their C names. A name missing from the installed headers fails the build:
 * the SDK is older than this crate requires.
 *
 * The core's codec headers (codec.h, control.h, buf.h, kvp.h, wire.h,
 * vi64.h) are not part of this tier. */

