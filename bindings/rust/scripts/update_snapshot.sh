#!/usr/bin/env bash
# Regenerate the docs.rs snapshot (moq5-sys/docs/bindings.rs, with its
# provenance header, and docs/preambles.md) from a build against an installed
# SDK. tests/snapshot.rs then holds both equal to a fresh generation on every
# qualified target.
#
#   update_snapshot.sh <sdk-prefix>
#
# Environment: CARGO (default cargo), LIBCLANG_PATH as bindgen needs it.
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
PREFIX=${1:?sdk prefix}
CARGO=${CARGO:-cargo}
export MOQ_PREFIX="$PREFIX"
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$HERE/target}

"$CARGO" build --manifest-path "$HERE/Cargo.toml" -p moq5-sys
generated=$(ls -t "$CARGO_TARGET_DIR"/debug/build/moq5-sys-*/out/bindings.rs | head -1)
preambles=$(dirname "$generated")/preambles.md

commit=$(git -C "$HERE" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
if [ -n "$(git -C "$HERE" status --porcelain -- "$HERE/../../core/include" \
        "$HERE/../../service/include" "$HERE/../../media" 2>/dev/null)" ]; then
    commit="$commit (native headers modified in the worktree)"
fi
pc=""
for d in lib/pkgconfig lib64/pkgconfig; do
    [ -f "$PREFIX/$d/libmoq-service.pc" ] && pc="$PREFIX/$d/libmoq-service.pc" && break
done
[ -n "$pc" ] || { echo "update_snapshot.sh: no libmoq-service.pc under $PREFIX" >&2; exit 2; }
requires=$(sed -n 's/^Requires: *//p' "$pc")
target=$(rustc -vV | sed -n 's/^host: //p')
bindgen=$(awk '/^name = "bindgen"$/ { getline; sub(/^version = "/, ""); sub(/"$/, ""); print }' "$HERE/Cargo.lock")
libclang=${LIBCLANG_PATH:-"(clang-sys search)"}

{
    echo "// A snapshot of the generated bindings, compiled only under cfg(docsrs), where"
    echo "// no SDK is installed to generate them from. Regenerated by"
    echo "// scripts/update_snapshot.sh; tests/snapshot.rs holds it equal to a fresh"
    echo "// generation on every qualified target."
    echo "//"
    echo "// libmoq commit: $commit"
    echo "// SDK: libmoq-service.pc Requires: $requires"
    echo "// generated on: $target with bindgen $bindgen, libclang from $libclang"
    echo
    cat "$generated"
} > "$HERE/moq5-sys/docs/bindings.rs"
cp "$preambles" "$HERE/moq5-sys/docs/preambles.md"
echo "update_snapshot.sh: wrote $HERE/moq5-sys/docs/bindings.rs and docs/preambles.md from $(dirname "$generated")"
