//! The docs.rs snapshot equals a fresh generation: `docs/bindings.rs`, past
//! its provenance header, is byte for byte what the build script generated
//! from the installed headers on this target, and `docs/preambles.md` is the
//! header preambles it extracted. The row runs on every qualified target,
//! which is what lets the manifests restrict docs.rs to them.

const GENERATED: &str = include_str!(concat!(env!("OUT_DIR"), "/bindings.rs"));
const SNAPSHOT: &str = include_str!("../docs/bindings.rs");
const GENERATED_PREAMBLES: &str = include_str!(concat!(env!("OUT_DIR"), "/preambles.md"));
const SNAPSHOT_PREAMBLES: &str = include_str!("../docs/preambles.md");

/// The snapshot without its leading `//` provenance lines and the blank line
/// after them.
fn snapshot_body() -> &'static str {
    let mut rest = SNAPSHOT;
    loop {
        let line_end = rest.find('\n').map_or(rest.len(), |i| i + 1);
        let line = &rest[..line_end];
        if line.starts_with("//") || line.trim().is_empty() {
            rest = &rest[line_end..];
            if rest.is_empty() {
                return rest;
            }
        } else {
            return rest;
        }
    }
}

/// The first line at which two texts differ, 1-based, or the shorter
/// text's length when one is a prefix of the other.
fn first_difference(a: &str, b: &str) -> usize {
    a.lines()
        .zip(b.lines())
        .position(|(x, y)| x != y)
        .map_or(a.lines().count().min(b.lines().count()), |i| i + 1)
}

#[test]
fn snapshot_matches_the_generated_bindings() {
    let body = snapshot_body();
    assert!(
        GENERATED.starts_with("/* automatically generated by rust-bindgen"),
        "the generated file starts with bindgen's banner"
    );
    if body != GENERATED {
        panic!(
            "docs/bindings.rs differs from the generated bindings at line {} of the \
             body; regenerate it with scripts/update_snapshot.sh <sdk-prefix>",
            first_difference(body, GENERATED)
        );
    }
}

#[test]
fn snapshot_preambles_match_the_generated_preambles() {
    if SNAPSHOT_PREAMBLES != GENERATED_PREAMBLES {
        panic!(
            "docs/preambles.md differs from the generated preambles at line {}; \
             regenerate it with scripts/update_snapshot.sh <sdk-prefix>",
            first_difference(SNAPSHOT_PREAMBLES, GENERATED_PREAMBLES)
        );
    }
}
