typedef struct moq5_layout_entry {
    const char *name;   /* "type" or "type.field" or a V0 macro name */
    size_t      size;   /* sizeof for a type, 0 for a field, the value for a floor */
    size_t      align;  /* alignof for a type */
    size_t      offset; /* offsetof for a field */
} moq5_layout_entry_t;

