#ifndef MOQR_BIND_METADATA_H
#define MOQR_BIND_METADATA_H

#include <moq/relay/moqr_bind.h>

/* Private, non-installed bind/shard contract. All calls and references stay
 * on the binding's owner lane. Messages between shards must DEEP COPY bytes;
 * neither a reference nor its storage pointer may cross that boundary. */
#define MOQR_BIND_META_BYTES_MAX (UINT64_C(1) << 20)
#define MOQR_BIND_META_SET_MAX   (UINT32_C(1) << 16)

typedef enum moqr_bind_meta_state {
    MOQR_BIND_META_UNAVAILABLE = 0,
    MOQR_BIND_META_EMPTY,
    MOQR_BIND_META_PRESENT
} moqr_bind_meta_state_t;

struct moqr_bind_meta_blob;
typedef struct moqr_bind_meta_ref {
    moqr_bind_meta_state_t state;
    moq_version_t         wire_version;
    moqr_binding_t        source_binding;
    uint64_t              source_handle;
    uint64_t              source_generation;
    uint64_t              revision;
    moq_bytes_t           bytes;
    struct moqr_bind_meta_blob *storage;
} moqr_bind_meta_ref_t;

/* Source provenance above describes the received block, NOT current route
 * liveness: a WARM track can retain it after its source generation changes.
 * revision is local to this binding; zero means no state has been learned.
 * EMPTY is available across wire profiles. A nonempty set is kept exactly as
 * received with its wire_version; a reply converts the set's Key-Value-Pair
 * integers to its own draft when they differ (draft-16 QUIC varints, vi64 in
 * draft-18/22) and refuses one it cannot state exactly. This is not a
 * LOC/media conversion. */

/* Retain/release are nonallocating, memory-only. Retain requires an empty out;
 * release clears it. Release ALL manager-held pins before destroying b.
 * The bytes view remains valid for the lifetime of an owned reference. */
moqr_result_t moqr_bind_meta_retain(moqr_bind_t *b,
                                  const moqr_bind_meta_ref_t *borrowed,
                                  moqr_bind_meta_ref_t *out);
void moqr_bind_meta_release(moqr_bind_t *b, moqr_bind_meta_ref_t *ref);

/* Router callback only: retain the EXACT executing reply pin, including one
 * prepared before scalar FIFO parking. No latest lookup, core reentry or
 * allocation. The intent pointer must be the callback's current argument. */
moqr_result_t moqr_bind_meta_retain_executing(
    moqr_bind_t *b, const moqr_intent_t *intent, moqr_bind_meta_ref_t *out);

/* Full retained-track handle lookup, including WARM. Returns an owned ref;
 * missing metadata is UNAVAILABLE/revision 0, never fabricated EMPTY. The
 * caller must already hold a currently resolved track/demand identity. */
moqr_result_t moqr_bind_meta_latest(moqr_bind_t *b, moqr_track_t track,
                                  moqr_bind_meta_ref_t *out);

/* The set a reply this relay originates for `track` states (FETCH_OK,
 * TRACK_STATUS_OK): the recorded set, EMPTY when the binding does not manage
 * the source's metadata, otherwise UNAVAILABLE. Returns an owned ref. */
moqr_result_t moqr_bind_meta_reply(moqr_bind_t *b, moqr_track_t track,
                                   moqr_bind_meta_ref_t *out);

/* Replace the complete latest state after checking the exact LOCAL track and
 * current source generation. The local retained source must have opted into
 * MOQR_BINDING_TRACK_METADATA_MANAGED; a property-less direct source returns
 * WRONG_STATE without publishing. Remote provenance fields describe the
 * received block, while a shard requester uses its managed local pseudo-source.
 * The caller additionally validates its full
 * binding/request or demand identity. input is borrowed and copied before
 * returning; its storage/revision fields are not imported. On byte-capacity
 * or allocation failure, publish UNAVAILABLE and release the old directory
 * pin, but leave executing/deferred reply pins intact. out_revision then
 * identifies that unavailable state. STALE/INVAL/WRONG_STATE do not publish.
 * Call only outside an intent drain/change callback: the implementation seals
 * older reply intents before replacement. No wire ACK is generated by this
 * metadata operation itself. Managed provenance is never cleared after a copy
 * failure. Generic latest remains fail-closed; only an eligible ACCEPT_SUB
 * with an admitted direct source and no directory obligation can pin EMPTY. */
moqr_result_t moqr_bind_meta_replace(moqr_bind_t *b, moqr_track_t track,
                                   uint64_t track_gen,
                                   const moqr_bind_meta_ref_t *input,
                                   uint64_t now_us, uint64_t *out_revision);

/* One change sink, installed before pumping. Called synchronously after a
 * replacement, on the owner lane. latest is borrowed for this call only;
 * retain it to coalesce one latest-state obligation per live demand. The
 * callback may retain/release pins, but must not reenter core/session/bind or
 * touch a channel. Initial ACK pins are separate and must not be overwritten.
 * Queue this state in the existing demand FIFO before dependent fill results;
 * requester copy/UNAVAILABLE application must precede consuming those results.
 * No callback is made for mere release or memory-only destruction. */
typedef void (*moqr_bind_meta_changed_fn)(void *ctx, moqr_track_t track,
                                        uint64_t track_gen,
                                        const moqr_bind_meta_ref_t *latest);
moqr_result_t moqr_bind_meta_set_observer(moqr_bind_t *b,
                                         moqr_bind_meta_changed_fn changed,
                                         void *ctx);

#endif
