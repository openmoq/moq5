/* Layout of every record the moq5 crate reads or writes, as the C compiler
 * sees it: sizeof and alignof per struct, offsetof per field, and the frozen
 * v0 floors. The Rust side compares each entry with the bindgen-generated
 * types; a name on one side and not the other is a failure too. */

