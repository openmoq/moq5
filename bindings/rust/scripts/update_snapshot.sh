#!/usr/bin/env bash
# Regenerate the docs.rs snapshot (moq5-sys/docs/bindings.rs and
# bindings_player.rs, each with its provenance header, and docs/preambles.md
# and preambles_player.md) from a build against an installed SDK with the
# player. tests/snapshot.rs then holds them equal to a fresh generation on
# every qualified target.
#
#   update_snapshot.sh <sdk-prefix>
#
# Environment: CARGO (default cargo), LIBCLANG_PATH as bindgen needs it.
set -euo pipefail
HERE=$(cd "$(dirname "$0")/.." && pwd)
PREFIX=${1:?sdk prefix}
CARGO=${CARGO:-cargo}
export MOQ_PREFIX="$PREFIX"
export CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-$HERE/target}

"$CARGO" build --manifest-path "$HERE/Cargo.toml" -p moq5-sys --features player
generated=$(ls -t "$CARGO_TARGET_DIR"/debug/build/moq5-sys-*/out/bindings_player.rs | head -1)
out=$(dirname "$generated")

commit=$(git -C "$HERE" rev-parse --short=12 HEAD 2>/dev/null || echo unknown)
if [ -n "$(git -C "$HERE" status --porcelain -- "$HERE/../../core/include" \
        "$HERE/../../service/include" "$HERE/../../media" 2>/dev/null)" ]; then
    commit="$commit (native headers modified in the worktree)"
fi
pc=""
for d in lib/pkgconfig lib64/pkgconfig; do
    [ -f "$PREFIX/$d/libmoq-service.pc" ] && pc="$PREFIX/$d/libmoq-service.pc" && break
done
[ -n "$pc" ] || { echo "update_snapshot.sh: no libmoq-service.pc under $PREFIX" >&2; exit 2; }
requires=$(sed -n 's/^Requires: *//p' "$pc")
target=$(rustc -vV | sed -n 's/^host: //p')
bindgen=$(awk '/^name = "bindgen"$/ { getline; sub(/^version = "/, ""); sub(/"$/, ""); print }' "$HERE/Cargo.lock")
# The libclang that generated them: where it was found, and its version,
# which decides whether macro constants carry documentation.
libclang="from ${LIBCLANG_PATH:-"(clang-sys search)"} ($(cat "$out/libclang.txt"))"

snapshot() {   # snapshot <generated file> <snapshot file> <what it holds>
    {
        echo "// A snapshot of the generated $3, compiled only under cfg(docsrs), where"
        echo "// no SDK is installed to generate them from. Regenerated by"
        echo "// scripts/update_snapshot.sh; tests/snapshot.rs holds it equal to a fresh"
        echo "// generation on every qualified target."
        echo "//"
        echo "// libmoq commit: $commit"
        echo "// SDK: libmoq-service.pc Requires: $requires"
        echo "// generated on: $target with bindgen $bindgen, libclang $libclang"
        echo
        cat "$1"
    } > "$2"
}
snapshot "$out/bindings.rs" "$HERE/moq5-sys/docs/bindings.rs" "bindings"
snapshot "$out/bindings_player.rs" "$HERE/moq5-sys/docs/bindings_player.rs" "player bindings"
cp "$out/preambles.md" "$HERE/moq5-sys/docs/preambles.md"
cp "$out/preambles_player.md" "$HERE/moq5-sys/docs/preambles_player.md"
echo "update_snapshot.sh: wrote $HERE/moq5-sys/docs/{bindings,bindings_player}.rs and docs/{preambles,preambles_player}.md from $out"
